//! The learned scorer (POST-R103, R104, R107, R108), the rule ledger and the built-in constants.

use std::collections::{BTreeSet, HashMap};

use jr_formats::post_policy;
use jr_posts::evaluate::Constants;
use jr_posts::evaluate::scorer::{
    self, Candidate, ContextKey, Feature, Model, Resolution, cluster_areas, cluster_posts,
};
use serde_json::Value;

const GOLDEN: &str = include_str!("data/post-scorer-golden.json");
const LEDGER: &str = include_str!("../../../docs/rules/posts.md");

fn learned() -> jr_posts::evaluate::LearnedConstants {
    Constants::builtin().learned
}

fn text(value: &Value) -> Option<String> {
    value.as_str().map(str::to_owned)
}

/// Generated by `uv run python -m post_scorer.golden` (jrutil/scripts/post-scorer) from the
/// Ústecký candidate table and the production model; F# matched it to 1e-9.
#[test]
fn post_r107_r108_learned_scorer_matches_the_python_reference_on_the_golden_stops() {
    let root: Value = serde_json::from_str(GOLDEN).unwrap();
    let parsed = post_policy::parse_model(root["model"].clone()).expect("model");
    // The fixture scores feature vectors as given.
    let model = Model::from_parts(&parsed, vec![Feature::Side; parsed.stage1.features.len()]);
    let mut compared = 0;
    let mut worst: f64 = 0.0;
    for stop in root["stops"].as_array().unwrap() {
        let contexts: Vec<ContextKey> = stop["contexts"]
            .as_array()
            .unwrap()
            .iter()
            .map(|c| ContextKey {
                context: text(&c["context_id"]).unwrap(),
                previous: text(&c["previous_stop"]),
                next: text(&c["next_stop"]),
                stop_post_count: c["stop_post_count"].as_u64().unwrap() as usize,
            })
            .collect();
        let rows = stop["candidates"].as_array().unwrap();
        let candidates: Vec<Candidate> = rows
            .iter()
            .map(|c| Candidate {
                context: text(&c["context_id"]).unwrap(),
                hypothesis: text(&c["hypothesis_id"]).unwrap(),
                post: text(&c["post_id"]).unwrap(),
                area: text(&c["area_id"]).unwrap(),
                is_platform: c["is_platform"].as_bool().unwrap(),
                features: c["features"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .map(|v| v.as_f64().unwrap())
                    .collect(),
            })
            .collect();
        let expected: HashMap<(String, String), (f64, f64)> = rows
            .iter()
            .map(|c| {
                (
                    (
                        text(&c["context_id"]).unwrap(),
                        text(&c["hypothesis_id"]).unwrap(),
                    ),
                    (
                        c["stage1_probability"].as_f64().unwrap(),
                        c["stage2_probability"].as_f64().unwrap(),
                    ),
                )
            })
            .collect();
        let (ordered, stage1, stage2) =
            scorer::stop_probabilities(&model, &contexts, candidates.clone());
        for (index, candidate) in ordered.iter().enumerate() {
            let (first, second) =
                expected[&(candidate.context.clone(), candidate.hypothesis.clone())];
            worst = worst
                .max((first - stage1[index]).abs())
                .max((second - stage2[index]).abs());
        }
        let decisions: HashMap<String, scorer::Decision> =
            scorer::score_stop(&model, &contexts, candidates, &learned())
                .into_iter()
                .map(|d| (d.context.clone(), d))
                .collect();
        for d in stop["decisions"].as_array().unwrap() {
            let actual = &decisions[d["context_id"].as_str().unwrap()];
            let resolution = match actual.resolution {
                Resolution::Physical => "Physical",
                Resolution::Area => "Area",
                Resolution::Abstain => "Abstain",
            };
            assert_eq!(d["resolution"].as_str().unwrap(), resolution);
            assert_eq!(text(&d["hypothesis_id"]), actual.hypothesis);
            worst = worst
                .max((d["post_probability"].as_f64().unwrap() - actual.post_probability).abs())
                .max((d["area_probability"].as_f64().unwrap() - actual.area_probability).abs());
            compared += 1;
        }
    }
    assert!(compared > 100, "golden fixture too small: {compared}");
    assert!(worst <= 1e-9, "largest probability difference {worst}");
}

#[test]
fn post_r103_posts_never_contain_one_source_twice_or_two_local_refs() {
    let sources = |names: &[&str]| -> Vec<Vec<String>> {
        names.iter().map(|name| vec![(*name).to_owned()]).collect()
    };
    let posts = cluster_posts(
        &[50.0, 50.00005, 50.00002, 50.00003],
        &[14.0, 14.0, 14.00005, 14.00002],
        &sources(&["S", "S", "T", "U"]),
        &[Some("1".into()), None, Some("2".into()), None],
        &learned(),
    );
    assert_ne!(posts[0], posts[1]);
    assert_ne!(posts[0], posts[2]);
    assert_eq!(posts.len(), 4);
}

#[test]
fn post_r103_posts_farther_apart_than_25_m_stay_separate() {
    let sources = vec![vec!["S".to_owned()], vec!["T".to_owned()]];
    let far = cluster_posts(
        &[50.0, 50.0003],
        &[14.0, 14.0],
        &sources,
        &[None, None],
        &learned(),
    );
    assert_ne!(far[0], far[1]);
    let near = cluster_posts(
        &[50.0, 50.0001],
        &[14.0, 14.0],
        &sources,
        &[None, None],
        &learned(),
    );
    assert_eq!(near[0], near[1]);
}

#[test]
fn post_r104_areas_never_mix_tram_and_road_posts() {
    let areas = cluster_areas(
        &[50.0, 50.0001, 50.0002],
        &[14.0, 14.0, 14.0],
        &["road", "tram", "road"],
        &learned(),
    );
    assert_ne!(areas[0], areas[1]);
    assert_eq!(areas[0], areas[2]);
    let any = cluster_areas(
        &[50.0, 50.0001],
        &[14.0, 14.0],
        &["road", "any"],
        &learned(),
    );
    assert_eq!(any[0], any[1]);
}

#[test]
fn post_r108_uncertain_contexts_fall_back_to_the_area_then_abstain() {
    let model = |simple: f64, area: Option<f64>| Model {
        features: vec![Feature::Side],
        stage1: scorer::Stage {
            mean: vec![0.0],
            scale: vec![1.0],
            weights: vec![0.0],
            null_utility: -10.0,
        },
        stage2: scorer::Stage {
            mean: vec![0.0; 7],
            scale: vec![1.0; 7],
            weights: vec![0.0; 7],
            null_utility: -10.0,
        },
        simple,
        complex: 0.9,
        area,
    };
    let contexts = [ContextKey {
        context: "c".into(),
        previous: Some("p".into()),
        next: Some("n".into()),
        stop_post_count: 2,
    }];
    let candidate = |hypothesis: &str, post: &str| Candidate {
        context: "c".into(),
        hypothesis: hypothesis.into(),
        post: post.into(),
        area: "A".into(),
        is_platform: false,
        features: vec![0.0],
    };
    let decide = |model: Model| {
        scorer::score_stop(
            &model,
            &contexts,
            vec![candidate("h1", "P1"), candidate("h2", "P2")],
            &learned(),
        )
        .remove(0)
    };
    let area = decide(model(0.9, Some(0.8)));
    assert_eq!(area.resolution, Resolution::Area);
    assert_eq!(area.hypothesis.as_deref(), Some("h1"));
    assert_eq!(decide(model(0.9, None)).resolution, Resolution::Abstain);
    assert_eq!(decide(model(0.4, None)).resolution, Resolution::Physical);
}

#[test]
fn every_rule_has_a_heading_in_the_ledger() {
    let headings: BTreeSet<&str> = LEDGER
        .lines()
        .filter_map(|line| line.strip_prefix("#### "))
        .filter_map(|heading| heading.split_whitespace().next())
        .collect();
    let all = jr_posts::estimate::rules();
    let missing: Vec<&str> = all
        .iter()
        .map(|rule| rule.id)
        .filter(|id| !headings.contains(id))
        .collect();
    assert!(missing.is_empty(), "undocumented rules: {missing:?}");
    let mut seen = BTreeSet::new();
    for rule in &all {
        assert!(seen.insert(rule.id), "{} is declared twice", rule.id);
        assert!(!rule.summary.is_empty());
    }
}

