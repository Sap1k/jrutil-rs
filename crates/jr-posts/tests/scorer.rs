    let constants = Constants::builtin();
    assert_eq!(constants.modes.inheritance_radius_m, 15.0);
    assert_eq!(constants.geometry.alignment_range_deg, 90.0);
    assert_eq!(constants.geometry.proximity_range_m, 50.0);
